# eCom/models.py
from django.db import models
from django.conf import settings


class ResetToken(models.Model):
    '''
    Model storing the token for use in resetting passwords.

    Fields:
    - user: obtained from the authorised user model built-in from Django
    - token: CharField for storing the token generated by gen_reset_url(user)
      in utils module.
    - expiry_date: DateTimeField used to store the date and time when the token
      expires.
    - used: BooleanField to determine if the token was used or not.

    Methods:
    - __str__: Returns a string representation of the model.
    '''

    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE)
    token = models.CharField(max_length=500)
    expiry_date = models.DateTimeField()
    used = models.BooleanField(default=False)

    def __str__(self):
        return f"ResetToken(user={self.user.username}, token={self.token[:10]}..., used={self.used})"


class Store(models.Model):
    '''
    Model representing the sotres in the app.

    Fields:
    - name: CharField for the name of the store.
    - description: TextField for the description of the store.
    - user: From the authorised user model built into Django to conntect a
      specific user to the store.

    Methods:
    - __str__: returns a string representation of the store name.

    Subclass:
    - Meta: contains the permissions for users interacting with the store
      model.
    '''

    name = models.CharField(max_length=100)
    description = models.TextField(blank=True)
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE)

    def __str__(self):
        return self.name

    class Meta:
        default_permissions = ()
        permissions = [
            ("add_stores", "Can add stores"),
            ("change_stores", "Can change stores"),
            ("delete_stores", "Can delete stores"),
            ("view_stores", "Can view stores"),
        ]


class Product(models.Model):
    '''
    Model representing products to be added to stores.

    Fields:
    - name: CharField for the product name.
    - description: TextField for the product description.
    - quantity: PositiveIntegerField to store the quantity of the product.
    - price: DecimalField to store the price of the product.
    - vendor: A foreign key to link the specific store where the product is
      sold from.

    Methods:
    - __str__: Returns a string representing the product name.

    Subclass:
    - Meta: Contains permissions for the user interacting with the product
      model.
    '''

    name = models.CharField(max_length=255)
    description = models.TextField(blank=True)
    quantity = models.PositiveIntegerField()
    price = models.DecimalField(max_digits=10, decimal_places=2)
    vendor = models.ForeignKey(
        Store,
        on_delete=models.CASCADE,
        related_name="products"
    )

    def __str__(self):
        return self.name

    class Meta:
        default_permissions = ()
        permissions = [
            ("add_products", "Can add products"),
            ("change_products", "Can change products"),
            ("delete_products", "Can delete products"),
            ("view_products", "Can view products"),
        ]


class Order(models.Model):
    '''
    Model representing orders placed by buyers in the app.

    Fields:
    - created_on = DateTimeField automatically sets the current date at
      placement of order.
    - total_price: DecimalField where the total price of the order is stored.
    - user: Obtained from authorised user model built into Django. Stores the
      user currently logged in which placed the order.

    Methods:
    - __str__: Returns a string representation of the order and who placed it.
    '''

    created_on = models.DateTimeField(auto_now_add=True)
    total_price = models.DecimalField(
        max_digits=10,
        decimal_places=2,
        default=0.00
    )
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE)

    def __str__(self):
        return f"Order number: {self.id} by {self.user.username}."


class OrderItem(models.Model):
    '''
    Model representing items in the cart that was purchased by the user per
    order.

    Fields:
    - order: Foreign key to link the order to the order items.
    - product: CharField to store the product which was purchased.
    - price: DecimalField to store the price of each product.
    - quantity: PositiveIntegerField to store the quantity of each product
      that was purchased.
    - subtotal: DecimalField to store the subtotal (product price * quantity)
      of each line item purchased.

    Methods:
    - __str__: Returns a string representation of the line items and order.
    '''
    order = models.ForeignKey(
        Order,
        on_delete=models.CASCADE,
        related_name="items"
    )
    product = models.ForeignKey(Product, on_delete=models.SET_NULL, null=True)
    product_name = models.CharField(max_length=255)
    price = models.DecimalField(max_digits=10, decimal_places=2)
    quantity = models.PositiveIntegerField(default=1)
    subtotal = models.DecimalField(max_digits=10, decimal_places=2)

    def __str__(self):
        return f"{self.quantity} x {self.product.name} (Order {self.order.id})"


class Review(models.Model):
    '''
    Model representing the reviews that can be created for a product.

    Fields:
    - user: Obtained from authorised user model built into Django and stores
      the logged in user that created the review.
    - product: ForeignKey linking the product that is reviewed.
    - title: CharField storing the title of the review.
    - comments: TextField storing the comments left by the user.
    - rating: PositiveIntegerField storing the rating from 1 - 5 given by the
      user.
    - is_verified: BooleanField to check if the review is verified or not. A
      verified review means that the user has already purchased the product.
    - created_on: DateTimeField that automatically stores the current date and
      time that the review was created.

    Methods:
    - __str__: Returns as string representation fo the title of the review.
    '''

    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
    )
    product = models.ForeignKey(Product, on_delete=models.CASCADE)
    title = models.CharField(max_length=255)
    comments = models.TextField(blank=True)
    rating = models.PositiveIntegerField()
    is_verified = models.BooleanField(default=False)
    created_on = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return self.title
